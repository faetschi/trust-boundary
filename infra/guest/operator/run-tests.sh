  {
    printf '\n#### %s  %s\n\n' "$1" "$5"
    printf 'Command: `%s`\n\nExpected: %s. Got rc=%s.\n\n```\n%s\n```\n' "$2" "$3" "$4" "$o"
  } >>"$OUT.body"
  printf '%-5s %s\n' "$5" "$1"
}
