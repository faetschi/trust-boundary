q() { local s="" a; for a in "$@"; do s="$s $(printf '%q' "$a")"; done; printf '%s' "$s"; }
# t <id> <expect-rc> <expect-regex|-> <op args...>
t() {
  local id=$1 want=$2 rx=$3 out rc ok=FAIL args; shift 3
  N=$((N + 1)); args=$(q "$@")
  out=$(g "sudo -n $OP$args 2>&1; rc=\$?; printf '\\n[rc=%s]\\n' \$rc")
  rc=$(printf '%s\n' "$out" | sed -n 's/^\[rc=\([0-9]*\)\]$/\1/p' | tail -1)
  out=$(printf '%s\n' "$out" | sed '/^\[rc=[0-9]*\]$/d')
  if [[ $rc == "$want" && ( $rx == - || $out =~ $rx ) ]]; then ok=PASS; PASS=$((PASS + 1)); else FAIL=$((FAIL + 1)); fi
  rec "$id" "sudo -n $OP$args" "rc=$want${rx:+, output ~ /$rx/}" "$rc" "$ok" "$out"
}
# r <id> <expect-rc> <expect-regex|-> <guest command>   (setup / inspect, plain guest command)
r() {
  local id=$1 want=$2 rx=$3 cmd=$4 out rc ok=FAIL
  N=$((N + 1))
  out=$(g "$cmd; rc=\$?; printf '\\n[rc=%s]\\n' \$rc")
  rc=$(printf '%s\n' "$out" | sed -n 's/^\[rc=\([0-9]*\)\]$/\1/p' | tail -1)
  out=$(printf '%s\n' "$out" | sed '/^\[rc=[0-9]*\]$/d')
  if [[ $rc == "$want" && ( $rx == - || $out =~ $rx ) ]]; then ok=PASS; PASS=$((PASS + 1)); else FAIL=$((FAIL + 1)); fi
  rec "$id" "$cmd" "rc=$want${rx:+, output ~ /$rx/}" "$rc" "$ok" "$out"
}
rec() {   # id cmd expect rc ok output
